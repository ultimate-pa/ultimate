/**
 * An independence relation that implements an SMT-based inclusion or equality check on the semantics.
 *
 * It is recommended to wrap this relation in a {@link CachedIndependenceRelation} for better performance.
 *
 * @author Dominik Klumpp (klumpp@informatik.uni-freiburg.de)
 *
 * @param <L>
 *            The type of letters whose independence is checked.
 */
public class SemanticIndependenceRelation<L extends IAction> implements IIndependenceRelation<IPredicate, L> {
	/**
	 * Specifies which kind of independence conditions should be generated by the symbolic counterpart of a semantic
	 * independence relation (see {@link IIndependenceRelation#getSymbolicRelation()}).
	 */
	public enum IndependenceConditions {
		/**
		 * No independence conditions can be generated.
		 */
		NONE(false, false),
		/**
		 * Generate sufficient conditions for independence.
		 */
		SUFFICIENT(false, true),
		/**
		 * Generate sufficient conditions for independence, taking into account known conditions.
		 */
		SUFFICIENT_WITH_CONTEXT(true, true),
		/**
		 * Generate necessary-and-sufficient conditions for independence.
		 */
		NECESSARY_AND_SUFFICIENT(true, false);

		private final boolean mRequiresPredicateFactory;
		private final boolean mRequiresConditionGenerator;

		IndependenceConditions(final boolean requiresPredicateFactory, final boolean requiresConditionGenerator) {
			mRequiresPredicateFactory = requiresPredicateFactory;
			mRequiresConditionGenerator = requiresConditionGenerator;
		}

		public boolean requiresPredicateFactory() {
			return mRequiresPredicateFactory;
		}

		public boolean requiresConditionGenerator() {
			return mRequiresConditionGenerator;
		}
	}

	private static final SimplificationTechnique SIMPLIFICATION_TECHNIQUE = SimplificationTechnique.SIMPLIFY_DDA;

	// Dominik 2025-04-24: We globally disable auxvar elimination for now, as the overhead is quite horrible.
	// The elimination was disabled before (in commit b1b9470223) but ignorantly enabled again (in commit 0918a82cb).
	// The consequences can be seen in the significant CPU time increase for GemCutter from SV-COMP'24 to '25.
	// Before enabling this again, please benchmark the impact, and don't forget to update this comment.
	//
	// Introducing this constant as a global switch allows us to preserve the logic below that is based on
	// considerations about when elimination is at all worthwhile, in case it is ever enabled again.
	private static final boolean ENABLE_AUXVAR_ELIMINATION = false;

	private final IUltimateServiceProvider mServices;
	private final ILogger mLogger;
	private final ManagedScript mManagedScript;
	private final boolean mConditional;
	private final boolean mSymmetric;

	private final IndependenceConditions mSymbolicIndependenceMode;
	private final BasicPredicateFactory mPredicateFactory;
	private final SemanticIndependenceConditionGenerator mIndependenceGenerator;

	private final Statistics mStatistics = new Statistics();

	/**
	 * Create a new variant of the semantic independence relation.
	 *
	 * The returned relation will not offer a symbolic counterpart via {@link #getSymbolicRelation()}. To support
	 * symbolic relations, call one of the other constructors.
	 *
	 * @param mgdScript
	 *            A script that will be used to construct and solve the required SMT queries for independence checks
	 * @param conditional
	 *            If set to true, the relation will be conditional: It will use the given {@link IPredicate} as context
	 *            to enable additional commutativity. This subsumes the non-conditional variant.
	 * @param symmetric
	 *            If set to true, the relation will check for full commutativity. If false, only semicommutativity is
	 *            checked, which subsumes full commutativity.
	 */
	public SemanticIndependenceRelation(final IUltimateServiceProvider services, final ManagedScript mgdScript,
			final boolean conditional, final boolean symmetric) {
		this(services, mgdScript, conditional, symmetric, IndependenceConditions.NONE, null, null);
	}

	/**
	 * Create a new variant of the semantic independence relation.
	 *
	 * @param mgdScript
	 *            A script that will be used to construct and solve the required SMT queries for independence checks
	 * @param conditional
	 *            If set to true, the relation will be conditional: It will use the given {@link IPredicate} as context
	 *            to enable additional commutativity. This subsumes the non-conditional variant.
	 * @param symmetric
	 *            If set to true, the relation will check for full commutativity. If false, only semicommutativity is
	 *            checked, which subsumes full commutativity.
	 * @param symbolicIndependenceMode
	 *            Determines whether the relation offers a symbolic counterpart via {@link #getSymbolicRelation()}, and
	 *            if so, what kind of independence conditions are generated.
	 * @param predicateFactory
	 *            Used for the symbolic relation returned by {@link #getSymbolicRelation()}.
	 *
	 *            See {@link IndependenceConditions#requiresPredicateFactory()
	 *            symbolicIndependence.requiresPredicateFactory()}.
	 * @param independenceGenerator
	 *            Used for the symbolic relation returned by {@link #getSymbolicRelation()}.
	 *
	 *            See {@link IndependenceConditions#requiresConditionGenerator()
	 *            symbolicIndependence.requiresConditionGenerator()}.
	 */
	public SemanticIndependenceRelation(final IUltimateServiceProvider services, final ManagedScript mgdScript,
			final boolean conditional, final boolean symmetric, final IndependenceConditions symbolicIndependenceMode,
			final BasicPredicateFactory predicateFactory,
			final SemanticIndependenceConditionGenerator independenceGenerator) {
		mServices = services;
		mManagedScript = mgdScript;
		mLogger = services.getLoggingService().getLogger(ModelCheckerUtils.PLUGIN_ID);

		mConditional = conditional;
		mSymmetric = symmetric;

		mSymbolicIndependenceMode = symbolicIndependenceMode;
		mPredicateFactory =
				symbolicIndependenceMode.requiresPredicateFactory() ? Objects.requireNonNull(predicateFactory) : null;
		mIndependenceGenerator =
				symbolicIndependenceMode.requiresConditionGenerator() ? Objects.requireNonNull(independenceGenerator)
						: null;
	}

	@Override
	public boolean isSymmetric() {
		return mSymmetric;
	}

	@Override
	public boolean isConditional() {
		return mConditional;
	}

	@Override
	public Dependence isIndependent(final IPredicate state, final L a, final L b) {
		mStatistics.startQuery();
		final var result = toDependence(contains(state, a, b));
		mStatistics.reportQuery(result, mConditional && state != null);
		return result;
	}

	@Override
	public ISymbolicIndependenceRelation<L, IPredicate> getSymbolicRelation() {
		return switch (mSymbolicIndependenceMode) {
		case NONE -> null;
		case SUFFICIENT -> new ConditionGeneratorIndependence(mIndependenceGenerator, false);
		case SUFFICIENT_WITH_CONTEXT -> new ConditionGeneratorIndependence(mIndependenceGenerator, true);
		case NECESSARY_AND_SUFFICIENT -> new SymbolicSemanticIndependence(mPredicateFactory);
		};
	}

	@Override
	public IStatisticsDataProvider getStatistics() {
		return mStatistics;
	}

	/**
	 * Implements {@link #isIndependent(IPredicate, IAction, IAction)} but returns {@code UNKNOWN} if the solver is
	 * unable to decide commutativity.
	 */
	private LBool contains(final IPredicate state, final L a, final L b) {
		final IPredicate context = mConditional ? state : null;
		if (context instanceof IMLPredicate) {
			// Locations will be ignored. However, using predicates with the same formula but different locations will
			// negatively affect cache efficiency. Hence output a warning message.
			mLogger.warn("Predicates with locations should not be used for independence.");
		}

		final var compositions = buildCompositions(a, b);
		final var tfAB = compositions.getFirst();
		final var tfBA = compositions.getSecond();

		final LBool subset = checkInclusionWithGuard(context, tfAB, tfBA);
		if (!mSymmetric) {
			return subset;
		}

		return and(subset, () -> checkInclusionWithGuard(context, tfBA, tfAB));
	}

	private final LBool checkInclusionWithGuard(final IPredicate context, final UnmodifiableTransFormula ab,
			final UnmodifiableTransFormula ba) {
		if (context != null && SmtUtils.isFalseLiteral(context.getFormula())) {
			return LBool.UNSAT;
		}

		if (mManagedScript.isLocked()) {
			mLogger.warn("Requesting ManagedScript unlock before implication check");
			final boolean unlocked = mManagedScript.requestLockRelease();
			if (!unlocked) {
				mLogger.warn("Failed to unlock ManagedScript. Unable to check independence, returning UNKNOWN.");
				return LBool.UNKNOWN;
			}
		}

		UnmodifiableTransFormula abWithGuard;
		if (context == null) {
			abWithGuard = ab;
		} else {
			final var guard = TransFormulaBuilder.constructTransFormulaFromPredicate(context, mManagedScript);

			// This composition should not introduce auxVars.
			// Avoid re-trying elimination of auxVars that already could not be eliminated from ab.
			final boolean tryAuxVarElimination = false;
			abWithGuard = compose(guard, ab, tryAuxVarElimination);
		}
		return TransFormulaUtils.checkImplication(abWithGuard, ba, mManagedScript);
	}

	private Pair<UnmodifiableTransFormula, UnmodifiableTransFormula> buildCompositions(final L a, final L b) {
		final UnmodifiableTransFormula tfA = a.getTransformula();
		final UnmodifiableTransFormula tfB = b.getTransformula();

		// Compose the two transition formulas in both orders.
		// For the composition a*b, only spend time eliminating auxVars if it might be used on the right-hand side of an
		// inclusion check, as auxVars on the left-hand side can be skolemized anyway.
		final UnmodifiableTransFormula transFormulaAB = compose(tfA, tfB, mSymmetric && ENABLE_AUXVAR_ELIMINATION);
		// For the composition b*a, always try to eliminate auxVars (if elimination is globally enabled), because it
		// always appears on the right-hand side of an inclusion check.
		final UnmodifiableTransFormula transFormulaBA = compose(tfB, tfA, ENABLE_AUXVAR_ELIMINATION);

		return new Pair<>(transFormulaAB, transFormulaBA);
	}

	private final UnmodifiableTransFormula compose(final UnmodifiableTransFormula first,
			final UnmodifiableTransFormula second, final boolean tryAuxVarElimination) {
		// no need to do simplification, result is only used in one implication check
		final boolean simplify = false;

		return TransFormulaUtils.sequentialComposition(mLogger, mServices, mManagedScript, simplify,
				tryAuxVarElimination, false, SIMPLIFICATION_TECHNIQUE, Arrays.asList(first, second));
	}

	private static LBool and(final LBool lhs, final Supplier<LBool> getRhs) {
		if (lhs == LBool.SAT) {
			return LBool.SAT;
		}
		final LBool rhs = getRhs.get();
		if (rhs == LBool.SAT) {
			return LBool.SAT;
		}
		if (lhs == LBool.UNSAT && rhs == LBool.UNSAT) {
			return LBool.UNSAT;
		}
		return LBool.UNKNOWN;
	}

	private static Dependence toDependence(final LBool value) {
		return switch (value) {
		case UNSAT -> Dependence.INDEPENDENT;
		case SAT -> Dependence.DEPENDENT;
		case UNKNOWN -> Dependence.UNKNOWN;
		};
	}

	/**
	 * A symbolic independence relation that synthesizes predicates under which two given actions would commute wrt.
	 * {@link SemanticIndependenceRelation}. Specifically, the predicates capture precisely what is needed for
	 * commutativity, as opposed to only a sufficient condition.
	 *
	 * @author Dominik Klumpp (klumpp@informatik.uni-freiburg.de)
	 */
	public class SymbolicSemanticIndependence implements ISymbolicIndependenceRelation<L, IPredicate> {
		private final BasicPredicateFactory mFactory;

		public SymbolicSemanticIndependence(final BasicPredicateFactory factory) {
			mFactory = factory;
		}

		@Override
		public IPredicate getCommutativityCondition(final IPredicate condition, final L a, final L b) {
			mStatistics.reportSymbolicConditionComputation();

			final var compositions = buildCompositions(a, b);
			final var tfAB = compositions.getFirst();
			final var tfBA = compositions.getSecond();

			final Term subset = computeInclusionTerm(tfAB, tfBA);
			final Term formula;
			if (!mSymmetric || SmtUtils.isFalseLiteral(subset)) {
				formula = subset;
			} else {
				final Term superset = computeInclusionTerm(tfBA, tfAB);
				formula = SmtUtils.and(mManagedScript.getScript(), subset, superset);
			}

			if (SmtUtils.isFalseLiteral(formula)) {
				// Filter false conditions and return "null" to indicate no condition could be found.
				return null;
			}
			return mFactory.newPredicate(formula);
		}

		private Term computeInclusionTerm(final UnmodifiableTransFormula lhs, final UnmodifiableTransFormula rhs) {
			final var difference = TransFormulaUtils.intersect(mManagedScript, lhs,
					TransFormulaUtils.negate(rhs, mManagedScript, mServices));

			// Although auxiliary variables can be skolemized, elimination and simplification yields a simpler
			// predicate. This also affects the trace proofs later on, especially if simplification can eliminate a
			// program variable from the condition.
			final boolean tryAuxVarElimination = true;
			final Term nonInclusion =
					TransFormulaUtils.computeGuardTerm(mServices, mManagedScript, difference, tryAuxVarElimination);

			final Term inclusion = SmtUtils.not(mManagedScript.getScript(), nonInclusion);

			// check the condition for satisfiability, and return "false" if it is unsatisfiable
			mManagedScript.lock(this);
			final LBool result = SmtUtils.checkSatTerm(mManagedScript.getScript(), inclusion);
			mManagedScript.unlock(this);

			return switch (result) {
			case UNKNOWN:
				mStatistics.reportUnknownSymbolicCondition();
				// $FALL-THROUGH$
			case SAT:
				yield inclusion;
			case UNSAT:
				yield mManagedScript.getScript().term(SMTLIBConstants.FALSE);
			};
		}

		@Override
		public boolean isSymmetric() {
			return mSymmetric;
		}

		@Override
		public boolean isConditional() {
			return false;
		}
	}

	/**
	 * A symbolic independence relation that uses an {@link SemanticIndependenceConditionGenerator} to generate a
	 * <em>sufficient</em> (but possibly not necessary) condition under which two given statements commute semantically.
	 *
	 * @author Dominik Klumpp (klumpp@informatik.uni-freiburg.de)
	 */
	public class ConditionGeneratorIndependence implements ISymbolicIndependenceRelation<L, IPredicate> {
		private static final boolean QUANTIFY_IRRELEVANT_CONTEXT_VARS = true;

		private final SemanticIndependenceConditionGenerator mGenerator;
		private final boolean mIsConditional;

		public ConditionGeneratorIndependence(final SemanticIndependenceConditionGenerator generator,
				final boolean conditional) {
			mGenerator = generator;
			mIsConditional = conditional;
			assert mGenerator.isSymmetric() == mSymmetric : "Symmetry of relation and generator does not match";
		}

		@Override
		public IPredicate getCommutativityCondition(final IPredicate condition, final L a, final L b) {
			mStatistics.reportSymbolicConditionComputation();

			if (mIsConditional && condition != null) {
				final var generated = mGenerator.generateCondition(condition, a.getTransformula(), b.getTransformula());
				if (generated == null) {
					return null;
				}
				if (!QUANTIFY_IRRELEVANT_CONTEXT_VARS) {
					return mPredicateFactory.and(condition, generated);
				}

				final var conjunction =
						SmtUtils.and(mManagedScript.getScript(), condition.getFormula(), generated.getFormula());
				final var irrelevantVars = condition.getVars().stream()
						.filter(pv -> !SemanticConditionEliminator.isRelevant(condition, a)
								&& !SemanticConditionEliminator.isRelevant(condition, b))
						.map(IProgramVar::getTermVariable).collect(Collectors.toList());
				final var quantified = SmtUtils.quantifier(mManagedScript.getScript(), QuantifiedFormula.EXISTS,
						irrelevantVars, conjunction);
				return mPredicateFactory.newPredicate(quantified);

			}
			return mGenerator.generateCondition(a.getTransformula(), b.getTransformula());
		}

		@Override
		public boolean isSymmetric() {
			return mSymmetric;
		}

		@Override
		public boolean isConditional() {
			return mIsConditional;
		}
	}

	private final static class Statistics extends TimedIndependenceStatisticsDataProvider {
		private static final String SYMBOLIC_CONDITION_COMPUTATIONS = "Symbolic Condition Computations";
		private static final String UNKNOWN_SYMBOLIC_CONDITIONS = "Symbolic Conditions with UNKNOWN Satisfiability";
		private int mSymbolicConditionComputations;
		private int mUnknownSymbolicConditions;

		private Statistics() {
			super(SemanticIndependenceRelation.class);
			declare(SYMBOLIC_CONDITION_COMPUTATIONS, () -> mSymbolicConditionComputations, KeyType.COUNTER);
			declare(UNKNOWN_SYMBOLIC_CONDITIONS, () -> mUnknownSymbolicConditions, KeyType.COUNTER);
		}

		private void reportSymbolicConditionComputation() {
			mSymbolicConditionComputations++;
		}

		private void reportUnknownSymbolicCondition() {
			mUnknownSymbolicConditions++;
		}
	}
}
